"""Drop-cap faces: one woff2 and font family per monochrome letter.

A page opens with one initial, so a 26-letter face is split into 26 files and the browser fetches
only the letter it shows (3–10 KB instead of 70–270 KB). The split does not depend on the census,
so `pnpm fonts:subset --initials-only` regenerates just these files and their stylesheet.

Originals live in harness/fonts/initials/ (not quartz/static, so the build never ships them) with
their provenance in LICENSES.md beside them; the stylesheet the newspaper layout reads is quartz/styles/fonts.initials.scss (generated here).
"""

from __future__ import annotations

import hashlib
from dataclasses import dataclass
from pathlib import Path

from fontTools import subset
from fontTools.pens.boundsPen import BoundsPen
from fontTools.ttLib import TTFont
from .faces import OUT_KV, ROOT, STYLES

INITIALS_DIR = ROOT / 'harness' / 'fonts' / 'initials'
# The EB Garamond Initials default arrives already subset (turntrout's A–Z build, renamed): one
# letter file and one ornament file per letter. They are copied to /fonts/ as they are.
GARAMOND_DIR = INITIALS_DIR / 'ebgaramond'
LETTERS = [chr(c) for c in range(0x41, 0x5B)]


@dataclass
class Initial:
  family: str  # CSS font-family; dropcap.scss maps a frontmatter `dropcap:` value to it
  source: str  # original in harness/fonts/initials
  enabled: bool = True
  note: str = ''
  # OFL Reserved Font Name: a subset is a Modified Version, so its name records are rewritten.
  rename: str = ''

  @property
  def stem(self) -> str:
    return Path(self.source).stem


# Monochrome initials only: colour is the theme's ink, so dark mode is the same file inverted.
# The two-layer EB Garamond Initials default is added by garamond_faces() below.
INITIALS: list[Initial] = [
  Initial(
    'Garden Initials Mono',
    'EBGaramondInitials.ttf',
    note='Duffner and Greinert, EB Garamond Initials 2023 (OFL, RFN "EB Garamond"), one layer',
    rename='Garden Initials Mono',
  ),
  Initial(
    'Goudy Initialen',
    'GoudyInitialen.ttf',
    note='Goudy 1913 (Lanston No. 296), Steffmann digitisation 2000',
  ),
  Initial('Yinit', 'Yinit.ttf', note='Haralambous 1994, public domain'),
  Initial(
    'Deutsche Zierschrift',
    'DeutscheZierschrift.ttf',
    note='Koch 1921, Steffmann digitisation 2002',
  ),
  Initial(
    'Kanzlei Initialen',
    'KanzleiInitialen.ttf',
    enabled=False,
    note='Steffmann 2002; the source design is unnamed, so it stays out until identified',
  ),
]

SCSS_HEADER = """// GENERATED by harness/fonts/subset.py (pnpm fonts:subset --initials-only). Do not edit.
// Drop-cap faces, one file per letter: a page fetches only the initial it
// opens with. Every file is served from the FONTS KV at /fonts/ (?v= is the file's content hash).
// font-display is block, not swap: a fallback initial would float a differently shaped box and
// reflow the opening lines when the real one lands. dropcap.scss picks the family per page.
// Explicit metrics keep the baseline at the em bottom, including cached font binaries.
// Monochrome letters use separate families without unicode-range so their line strut
// uses the initial font metrics, even though the subset has no space glyph.
"""


def normalise_metrics(font: TTFont) -> None:
  """Put the baseline at the bottom of a `line-height: 1` box on every platform.

  The sizing in column.scss assumes an initial's em box ends at its baseline (true of the EB
  Garamond Initials). These faces ship with assorted hhea/typo/win metrics, and macOS, Windows
  and FreeType each read a different pair, so the same CSS would float the letter a few pixels
  apart per platform. Ascent = UPM, descent = 0, line gap = 0 in all three, with USE_TYPO_METRICS
  set, makes the three agree; dropcap.scss then only needs each face's ink top and bottom.
  """
  upm = font['head'].unitsPerEm
  hhea, os2 = font['hhea'], font['OS/2']
  hhea.ascent, hhea.descent, hhea.lineGap = upm, 0, 0
  os2.sTypoAscender, os2.sTypoDescender, os2.sTypoLineGap = upm, 0, 0
  os2.usWinAscent, os2.usWinDescent = upm, 0
  # USE_TYPO_METRICS exists from OS/2 version 4; older tables lack the fields versions 2+ added.
  if os2.version < 4:
    os2.version = 4
    for field, value in (
      ('sxHeight', 0),
      ('sCapHeight', 0),
      ('usDefaultChar', 0),
      ('usBreakChar', 0x20),
      ('usMaxContext', 0),
    ):
      if not hasattr(os2, field):
        setattr(os2, field, value)
  os2.fsSelection |= 1 << 7


def rename(font: TTFont, family: str) -> None:
  """Replace the family in every record that carries it; the copyright and designer stay."""
  name = font['name']
  for rec in list(name.names):
    if rec.nameID in (16, 17, 21, 22):
      name.removeNames(nameID=rec.nameID)
  name.setName(family, 1, 3, 1, 0x409)
  name.setName('Regular', 2, 3, 1, 0x409)
  name.setName(f'{family} Regular', 4, 3, 1, 0x409)
  name.setName(family.replace(' ', '') + '-Regular', 6, 3, 1, 0x409)
  name.setName(f'{family} (from EB Garamond Initials)', 3, 3, 1, 0x409)
  name.names = [
    r for r in name.names if r.platformID == 3 or r.nameID not in (1, 3, 4, 6)
  ]


def subset_letter(src: Path, cp: int, family: str = '') -> TTFont:
  font = TTFont(src, recalcTimestamp=False)
  opts = subset.Options()
  opts.layout_features = []
  opts.hinting = False
  opts.glyph_names = True
  opts.desubroutinize = True
  opts.name_IDs = [0, 1, 2, 3, 4, 5, 6, 9, 10, 13, 14]
  opts.name_languages = ['*']
  opts.name_legacy = False
  opts.notdef_outline = False
  opts.recalc_bounds = True
  opts.recalc_timestamp = False
  opts.prune_unicode_ranges = True
  opts.drop_tables += ['gasp', 'DSIG', 'meta', 'FFTM', 'GDEF', 'GPOS', 'GSUB']
  opts.flavor = 'woff2'
  s = subset.Subsetter(options=opts)
  s.populate(unicodes=[cp])
  s.subset(font)
  normalise_metrics(font)
  if family:
    rename(font, family)
  font.flavor = 'woff2'
  return font


def verify_letter(path: Path, cp: int) -> int:
  f = TTFont(path)
  assert set(f.getBestCmap()) == {cp}, (
    f'{path.name}: cmap {sorted(f.getBestCmap())}'
  )
  assert f.flavor == 'woff2', path.name
  for t in ('fpgm', 'prep', 'cvt ', 'gasp', 'GSUB', 'GPOS'):
    assert t not in f, f'{path.name} kept {t}'
  upm = f['head'].unitsPerEm
  assert (f['hhea'].ascent, f['hhea'].descent) == (upm, 0), path.name
  return path.stat().st_size


def font_face(initial: Initial, versioned: str, cp: int) -> str:
  return (
    '@font-face {\n'
    f"  font-family: '{initial.family} {chr(cp)}';\n"
    f"  src: url('/fonts/{versioned}') format('woff2');\n"
    '  font-display: block;\n'
    '  ascent-override: 100%;\n'
    '  descent-override: 0%;\n'
    '  line-gap-override: 0%;\n'
    '}\n'
  )


def versioned_face(
  family: str, filename: str, path: Path, unicode_range: str
) -> str:
  digest = hashlib.sha256(path.read_bytes()).hexdigest()[:8]
  return (
    '@font-face {\n'
    f"  font-family: '{family}';\n"
    f"  src: url('/fonts/{filename}?v={digest}') format('woff2');\n"
    '  font-display: block;\n'
    f'  unicode-range: {unicode_range};\n'
    '}\n'
  )


def garamond_faces(scss: list[str], uploads: list[tuple[str, Path]]) -> None:
  """EB Garamond Initials (Duffner, OFL; renamed in the files): a letter face drawn over an
  ornament face. The letter face is one 5 KB file; the ornament is one file per letter."""
  letter = GARAMOND_DIR / 'initials-letter.woff2'
  key = 'GardenInitialsLetter.woff2'
  scss.append(versioned_face('Garden Initials Letter', key, letter, 'U+41-5A'))
  uploads.append((key, letter))
  for ch in LETTERS:
    path = GARAMOND_DIR / f'initials-ornament-{ch}.woff2'
    key = f'GardenInitialsOrnament.{ch}.woff2'
    scss.append(
      versioned_face('Garden Initials Ornament', key, path, f'U+{ord(ch):X}')
    )
    uploads.append((key, path))


def ink_bounds(src: Path) -> dict[str, tuple[float, float]]:
  """Each letter's ink top and bottom in em above the baseline (the foot of the normalised box),
  for column.scss's sizing: the ink, not the em, spans the first line's cap top to the last
  line's baseline. Tails below the baseline come out negative and are fitted into the block too."""
  font = TTFont(src)
  upm, cmap, glyphs = (
    font['head'].unitsPerEm,
    font.getBestCmap(),
    font.getGlyphSet(),
  )
  ink = {}
  for letter in LETTERS:
    pen = BoundsPen(glyphs)
    glyphs[cmap[ord(letter)]].draw(pen)
    _, y_min, _, y_max = pen.bounds
    ink[letter] = (round(y_max / upm, 3), round(y_min / upm, 3))
  return ink


def ink_map(inks: dict[str, dict[str, tuple[float, float]]]) -> str:
  """Sass map family -> letter -> (top bottom), read by dropcap.scss as fonts.$initials-ink."""
  rows = []
  for family, ink in inks.items():
    letters = ', '.join(f'{k}: ({t}, {b})' for k, (t, b) in ink.items())
    rows.append(f"  '{family}': ({letters}),\n")
  return '$initials-ink: (\n' + ''.join(rows) + ');\n'


def build_initials() -> list[tuple[str, Path]]:
  """Split every enabled face into per-letter woff2 files and write fonts.initials.scss.

  Returns the (key, path) pairs for publish(), like the face loop in cli.py.
  """
  OUT_KV.mkdir(parents=True, exist_ok=True)
  scss = [SCSS_HEADER]
  inks: dict[str, dict[str, tuple[float, float]]] = {}
  uploads: list[tuple[str, Path]] = []
  garamond_faces(scss, uploads)
  for initial in INITIALS:
    if not initial.enabled:
      continue
    src = INITIALS_DIR / initial.source
    inks[initial.family] = ink_bounds(src)
    total = 0
    for letter in LETTERS:
      cp = ord(letter)
      filename = f'{initial.stem}.{letter}.woff2'
      out = OUT_KV / filename
      subset_letter(src, cp, initial.rename).save(out)
      total += verify_letter(out, cp)
      digest = hashlib.sha256(out.read_bytes()).hexdigest()[:8]
      scss.append(font_face(initial, f'{filename}?v={digest}', cp))
      uploads.append((filename, out))
    print(
      f'{initial.source:<42} {src.stat().st_size:>7} → 26 letters, {total:>7} bytes, {total // 26:>5} avg'
    )
  scss.append(ink_map(inks))
  (STYLES / 'fonts.initials.scss').write_text(''.join(scss))
  print(f'wrote {STYLES / "fonts.initials.scss"}')
  return uploads
