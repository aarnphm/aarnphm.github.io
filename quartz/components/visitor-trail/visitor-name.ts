export function visitorHash(id: string) {
  return [...id].reduce((total, letter) => (Math.imul(total, 31) + letter.charCodeAt(0)) >>> 0, 0)
}

export function anonymousVisitor(id: string) {
  const random = trailRandom(visitorHash(id))
  return `${adjectives[Math.floor(random() * adjectives.length)]}-${animals[Math.floor(random() * animals.length)]}`
}
