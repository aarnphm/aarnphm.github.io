const BY_ID = new Map(PRESETS.map(preset => [preset.id.toLowerCase(), preset]))

export function resolvePreset(key: string): InitialPreset {
  return BY_ID.get(key.toLowerCase()) ?? PRESETS[hash(key) % PRESETS.length]
}

export function initialSettings(preset: InitialPreset, letter: string): Record<string, Setting> {
  return { ...preset.settings, text: letter.toUpperCase() }
}
